#!/usr/bin/env python3
"""Install the `github-copilot-cli` hook registration for the GitHub Copilot app / CLI.

Renders, from this directory's `hooks.yaml` and `agent-hooks.yaml`:

1. the GLOBAL hook file — exactly one of
   - `plugin`: `<bundle>/hooks.json` (or the path the bundle's `plugin.json` declares),
   - `repo`:   `<target-repo>/.github/hooks/safe-harness-copilot-cli.json`,
   - `user`:   `$COPILOT_HOME/hooks/` or `~/.copilot/hooks/safe-harness-copilot-cli.json`;
   (exactly one, so no event fires the adapter twice);
2. the AGENT-SCOPED H0 block in every framework orchestrator's agent file (between managed
   markers), in place in a bundle or as generated copies under `<target>/.github/agents/`.

Every entry runs the adapter with an explicit Python interpreter (default: the one running
this installer — run it from the harness venv) and absolute paths, so the output is
machine-specific: generated, never committed. Everything is validated before anything is
written; a refused run writes nothing.
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import sys
from pathlib import Path
from typing import Any, Mapping, Sequence

import subprocess

import yaml

ADAPTER_DIR = Path(__file__).resolve().parent
ADAPTER_ENTRY = ADAPTER_DIR / "adapter.py"
if str(ADAPTER_DIR) not in sys.path:
    sys.path.insert(0, str(ADAPTER_DIR))

from copilot_cli_adapter.core import EVENTS  # noqa: E402
from copilot_cli_adapter.layout import (  # noqa: E402
    FRAMEWORK_DIR_VARIABLE,
    LAYOUT_VARIABLES,
    LayoutError,
    read_env_file,
)

HOOKS_FILENAME = "safe-harness-copilot-cli.json"
PLUGIN_HOOKS_FILENAME = "hooks.json"
PLUGIN_MANIFEST = "plugin.json"
AGENT_SUFFIX = ".agent.md"
WORKFLOW_GLOB = "*.workflow.conf.yaml"
ORCHESTRATOR_KEY = "orchestrator"
HOOKS_KEY = "hooks"
FENCE = "---"
BLOCK_OPEN = (
    "# >>> safe-harness copilot-cli H0 — generated by "
    "adapters/github-copilot-cli/install.py; do not edit >>>"
)
BLOCK_CLOSE = "# <<< safe-harness copilot-cli H0 <<<"
HOOK_TARGETS = ("plugin", "repo", "user", "none")
HOOK_STYLES = ("exec", "shell")
_IO_ENVIRONMENT = {"PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1"}
HARNESS_PYTHON_VARIABLE = "SAF_HARNESS_PYTHON"
# The modules requirements.txt installs: the recorded hook interpreter must import them all,
# or every hook would fail (closed) at its first firing.
HARNESS_REQUIREMENT_MODULES = ("yaml", "jsonschema", "celpy")


class InstallError(ValueError):
    """Raised when the installation is refused; nothing has been written."""


# --- command rendering ----------------------------------------------------------------


def powershell_quote(value: str) -> str:
    """Quote one argument as a PowerShell single-quoted literal."""
    return "'" + value.replace("'", "''") + "'"


def adapter_args(
    event: str,
    framework_dir: str,
    agent: str | None = None,
    workspace_dir: str | None = None,
    layout: Mapping[str, str] | None = None,
) -> list[str]:
    args = [str(ADAPTER_ENTRY), "hook", "--event", event]
    if agent:
        args.extend(("--agent", agent))
    args.extend(("--framework-dir", framework_dir))
    if workspace_dir:
        args.extend(("--workspace-dir", workspace_dir))
    for variable in LAYOUT_VARIABLES:
        if layout and layout.get(variable):
            args.extend(("--layout", f"{variable}={layout[variable]}"))
    return args


def posix_command(python: str, args: Sequence[str]) -> str:
    return " ".join(shlex.quote(part) for part in (python, *args))


def powershell_command(python: str, args: Sequence[str]) -> str:
    return "& " + " ".join(powershell_quote(part) for part in (python, *args))


# --- the global hook file -------------------------------------------------------------


def load_registration(path: Path, key: str) -> Mapping[str, Mapping[str, Any]]:
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    events = (loaded or {}).get(key) if isinstance(loaded, Mapping) else None
    if not isinstance(events, Mapping) or not events:
        raise InstallError(f"{path} has no '{key}' event map")
    for event, spec in events.items():
        if event not in EVENTS:
            raise InstallError(f"{path} registers unknown event '{event}'")
        timeout = (spec or {}).get("timeoutSec")
        if not isinstance(timeout, int) or timeout <= 0:
            raise InstallError(f"{path} gives '{event}' no positive integer timeoutSec")
    return events


def layout_environment(
    framework_dir: Path, environment: Mapping[str, str], workspace_dir: Path | None = None
) -> dict[str, str]:
    """FRAMEWORK_DIR and every FRAMEWORK_*_DIR, as the harness will resolve them.

    Written into every hook's `env`, so nothing depends on the variables the app happens to
    inherit (no `setx`). `workspace_dir` overrides FRAMEWORK_WORKSPACE_DIR with an absolute
    path — the governed portfolio tree may live outside the framework checkout.
    """
    try:
        declared = read_env_file(framework_dir / ".env")
    except LayoutError as failure:
        raise InstallError(str(failure)) from failure
    values = {FRAMEWORK_DIR_VARIABLE: str(framework_dir)}
    if workspace_dir is not None:
        values["FRAMEWORK_WORKSPACE_DIR"] = str(workspace_dir)
    for variable in LAYOUT_VARIABLES:
        value = environment.get(variable, declared.get(variable))
        if value and variable not in values:
            values[variable] = value
    missing = [variable for variable in LAYOUT_VARIABLES if variable not in values]
    if missing:
        raise InstallError(
            f"the framework layout declares no {', '.join(missing)} "
            f"(neither in the environment nor in {framework_dir / '.env'})"
        )
    return values


def render_hooks_file(
    events: Mapping[str, Mapping[str, Any]],
    python: str,
    framework_dir: Path,
    environment: Mapping[str, str],
    style: str = "exec",
    workspace_dir: Path | None = None,
) -> dict[str, Any]:
    hooks: dict[str, list[dict[str, Any]]] = {}
    workspace = str(workspace_dir) if workspace_dir is not None else None
    for event, spec in events.items():
        args = adapter_args(event, str(framework_dir), workspace_dir=workspace)
        entry: dict[str, Any] = {"type": "command"}
        if style == "exec":
            entry.update({"exec": python, "args": args})
        else:
            entry.update(
                {
                    "bash": posix_command(python, args),
                    "powershell": powershell_command(python, args),
                }
            )
        entry.update(
            {
                "cwd": str(framework_dir),
                "env": {**environment, HARNESS_PYTHON_VARIABLE: python, **_IO_ENVIRONMENT},
                "timeoutSec": spec["timeoutSec"],
            }
        )
        hooks[event] = [entry]
    return {"version": 1, "hooks": hooks}


def resolve_interpreter(raw: str | None) -> str:
    """The interpreter every hook runs, refused unless it can import the harness requirements.

    Absolute but NOT symlink-resolved: a venv interpreter is a symlink whose own location
    selects the venv.
    """
    python = os.path.abspath(os.path.expanduser(raw)) if raw else os.path.abspath(sys.executable)
    if not Path(python).is_file():
        raise InstallError(f"the Python interpreter does not exist: {python}")
    probe = "import " + ", ".join(HARNESS_REQUIREMENT_MODULES)
    try:
        completed = subprocess.run(
            [python, "-c", probe],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
    except OSError as failure:
        raise InstallError(f"the Python interpreter cannot run: {python}: {failure}") from failure
    if completed.returncode != 0:
        raise InstallError(
            f"the Python interpreter {python} cannot import the harness requirements "
            f"({', '.join(HARNESS_REQUIREMENT_MODULES)}) — install requirements.txt into it, "
            "or pass --python <interpreter that has them>"
        )
    return python


# --- the agent-scoped H0 block --------------------------------------------------------


def orchestrator_slugs(workflows_dir: Path) -> list[str]:
    """An orchestrator is whoever the framework's workflow catalog names as one."""
    if not workflows_dir.is_dir():
        raise InstallError(f"no workflow catalog at {workflows_dir}")
    slugs: set[str] = set()
    for path in sorted(workflows_dir.rglob(WORKFLOW_GLOB)):
        workflow = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(workflow, Mapping):
            raise InstallError(f"the workflow at {path} is not an object")
        slug = workflow.get(ORCHESTRATOR_KEY)
        if slug is not None:
            if not isinstance(slug, str) or not slug:
                raise InstallError(f"the workflow at {path} names a non-slug orchestrator")
            slugs.add(slug)
    if not slugs:
        raise InstallError(f"the workflow catalog at {workflows_dir} names no orchestrator")
    return sorted(slugs)


def scoped_hooks(
    events: Mapping[str, Mapping[str, Any]],
    slug: str,
    python: str,
    framework_dir: Path,
    workspace_dir: Path | None = None,
    layout: Mapping[str, str] | None = None,
) -> dict[str, list[dict[str, Any]]]:
    """Agent-scoped entries carry no `env`: the layout travels as adapter arguments.

    `layout` is the SAME resolved layout the global hooks carry in their `env` (environment
    overrides included), so H0 opens the session where every later boundary looks for it.
    """
    hooks: dict[str, list[dict[str, Any]]] = {}
    workspace = str(workspace_dir) if workspace_dir is not None else None
    for event, spec in events.items():
        args = adapter_args(
            event, str(framework_dir), agent=slug, workspace_dir=workspace, layout=layout
        )
        hooks[event] = [
            {
                "type": "command",
                "command": posix_command(python, args),
                "windows": powershell_command(python, args),
                "timeoutSec": spec["timeoutSec"],
            }
        ]
    return hooks


def _split_frontmatter(text: str, where: str) -> tuple[list[str], str]:
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != FENCE:
        raise InstallError(f"{where} has no YAML frontmatter to carry the hook block")
    for index in range(1, len(lines)):
        if lines[index].strip() == FENCE:
            return lines[1:index], "".join(lines[index + 1 :])
    raise InstallError(f"{where} has a frontmatter block that is never closed")


def _without_managed_block(front: list[str], where: str) -> list[str]:
    kept: list[str] = []
    inside = False
    for line in front:
        marker = line.strip()
        if marker == BLOCK_OPEN:
            if inside:
                raise InstallError(f"{where} carries a damaged managed hook block (nested)")
            inside = True
        elif marker == BLOCK_CLOSE:
            if not inside:
                raise InstallError(f"{where} carries a damaged managed hook block (unopened)")
            inside = False
        elif not inside:
            kept.append(line)
    if inside:
        raise InstallError(f"{where} carries a damaged managed hook block (never closed)")
    return kept


def render_agent(source_text: str, hooks: Mapping[str, Any], where: str) -> str:
    """Inject (or replace) the managed H0 block; the agent's own keys and body are untouched."""
    front, body = _split_frontmatter(source_text, where)
    front = _without_managed_block(front, where)
    declared = yaml.safe_load("".join(front)) or {}
    if not isinstance(declared, Mapping):
        raise InstallError(f"{where} has frontmatter that is not a YAML object")
    if HOOKS_KEY in declared:
        raise InstallError(
            f"{where} already declares its own unmanaged '{HOOKS_KEY}:' block — a second "
            "one would be a duplicate key"
        )
    if front and not front[-1].endswith("\n"):
        front[-1] += "\n"
    block = yaml.safe_dump(
        {HOOKS_KEY: dict(hooks)},
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=2**31 - 1,
    )
    rendered = (
        f"{FENCE}\n" + "".join(front) + f"{BLOCK_OPEN}\n" + block + f"{BLOCK_CLOSE}\n"
        f"{FENCE}\n" + body
    )
    check_front, check_body = _split_frontmatter(rendered, where)
    parsed = yaml.safe_load("".join(check_front))
    if not isinstance(parsed, Mapping) or parsed.get(HOOKS_KEY) != dict(hooks):
        raise InstallError(f"{where} rendered a hook block that does not round-trip")
    if {key: value for key, value in parsed.items() if key != HOOKS_KEY} != dict(declared):
        raise InstallError(f"{where} rendered frontmatter that alters the agent's own keys")
    if check_body != body:
        raise InstallError(f"{where} rendered a body that differs from its source")
    return rendered


# --- planning -------------------------------------------------------------------------


def _plugin_hooks_path(bundle_dir: Path) -> Path:
    manifest = bundle_dir / PLUGIN_MANIFEST
    if manifest.is_file():
        try:
            declared = json.loads(manifest.read_text(encoding="utf-8")).get(HOOKS_KEY)
        except ValueError as failure:
            raise InstallError(f"{manifest} is not valid JSON: {failure}") from failure
        if isinstance(declared, str) and declared:
            return (bundle_dir / declared).resolve()
        if declared is not None:
            raise InstallError(
                f"{manifest} declares inline '{HOOKS_KEY}'; point it at a file "
                f"('{PLUGIN_HOOKS_FILENAME}') so this installer can render it"
            )
    return bundle_dir / PLUGIN_HOOKS_FILENAME


def _user_hooks_dir(environment: Mapping[str, str]) -> Path:
    home = environment.get("COPILOT_HOME")
    return (Path(home) if home else Path.home() / ".copilot") / "hooks"


def plan(arguments: argparse.Namespace, environment: Mapping[str, str]) -> dict[Path, str]:
    """Compute every file to write; raise `InstallError` before anything is written."""
    framework_dir = Path(os.path.abspath(os.path.expanduser(arguments.framework_dir)))
    if not framework_dir.is_dir():
        raise InstallError(f"the framework root does not exist: {framework_dir}")
    python = resolve_interpreter(arguments.python)
    bundle_dir = Path(os.path.abspath(arguments.bundle_dir)) if arguments.bundle_dir else None
    if bundle_dir is not None and not bundle_dir.is_dir():
        raise InstallError(f"the bundle directory does not exist: {bundle_dir}")
    target_repo = Path(os.path.abspath(arguments.target_repo or framework_dir))
    workspace_dir = None
    if arguments.workspace_dir:
        workspace_dir = Path(os.path.abspath(os.path.expanduser(arguments.workspace_dir)))
        if not workspace_dir.is_dir():
            raise InstallError(f"the workspace directory does not exist: {workspace_dir}")
    layout = layout_environment(framework_dir, environment, workspace_dir)

    outputs: dict[Path, str] = {}
    if arguments.hooks_target != "none":
        events = load_registration(ADAPTER_DIR / "hooks.yaml", "hooks")
        if arguments.hooks_target == "plugin":
            if bundle_dir is None:
                raise InstallError("--hooks-target plugin needs --bundle-dir")
            destination = _plugin_hooks_path(bundle_dir)
        elif arguments.hooks_target == "repo":
            destination = target_repo / ".github" / "hooks" / HOOKS_FILENAME
        else:
            destination = _user_hooks_dir(environment) / HOOKS_FILENAME
        rendered = render_hooks_file(
            events, python, framework_dir, layout, arguments.hook_style, workspace_dir
        )
        outputs[destination] = json.dumps(rendered, indent=2, ensure_ascii=False) + "\n"

    if not arguments.skip_agents:
        agent_events = load_registration(ADAPTER_DIR / "agent-hooks.yaml", "agentHooks")
        workflows_dir = (
            Path(os.path.abspath(arguments.workflows_dir))
            if arguments.workflows_dir
            else framework_dir / layout["FRAMEWORK_WORKFLOWS_DIR"]
        )
        if arguments.agents_dir:
            agents_dir = Path(os.path.abspath(arguments.agents_dir))
        elif bundle_dir is not None:
            agents_dir = bundle_dir / "agents"
        else:
            agents_dir = framework_dir / layout["FRAMEWORK_AGENTS_DIR"]
        if arguments.agents_dest:
            agents_dest = Path(os.path.abspath(arguments.agents_dest))
        elif bundle_dir is not None:
            agents_dest = agents_dir
        else:
            agents_dest = target_repo / ".github" / "agents"
        for slug in orchestrator_slugs(workflows_dir):
            source = agents_dir / f"{slug}{AGENT_SUFFIX}"
            if not source.is_file():
                raise InstallError(
                    f"orchestrator '{slug}' has no agent file at {source} — its "
                    "session-opening boundary (H0) would never fire"
                )
            hooks = scoped_hooks(agent_events, slug, python, framework_dir, workspace_dir, layout)
            outputs[agents_dest / f"{slug}{AGENT_SUFFIX}"] = render_agent(
                source.read_text(encoding="utf-8"), hooks, str(source)
            )
    return outputs


def _parse_arguments(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="install.py", description=__doc__.split("\n\n")[0]
    )
    parser.add_argument(
        "--framework-dir",
        required=True,
        help="the framework CHECKOUT (saf-agentic-organization root, with .env, workflows/, "
        "artifacts/, ...) — not the rendered plugin bundle",
    )
    parser.add_argument(
        "--workspace-dir",
        help="absolute governed workspace (portfolio) root; overrides FRAMEWORK_WORKSPACE_DIR",
    )
    parser.add_argument("--bundle-dir", help="a rendered Copilot plugin bundle root")
    parser.add_argument(
        "--hooks-target",
        choices=HOOK_TARGETS,
        default=None,
        help="where the global hook file goes (default: plugin with --bundle-dir, else repo)",
    )
    parser.add_argument("--target-repo", help="repository for --hooks-target repo / agents")
    parser.add_argument("--agents-dir", help="where the orchestrator agent sources are")
    parser.add_argument("--agents-dest", help="where the rendered orchestrator agents go")
    parser.add_argument("--workflows-dir", help="the framework's workflow catalog")
    parser.add_argument(
        "--python",
        help="absolute interpreter the hooks run; must import the harness requirements "
        "(default: the one running this script)",
    )
    parser.add_argument("--hook-style", choices=HOOK_STYLES, default="exec")
    parser.add_argument("--skip-agents", action="store_true", help="do not render H0 blocks")
    parser.add_argument("--dry-run", action="store_true", help="print the plan, write nothing")
    arguments = parser.parse_args(list(argv))
    if arguments.hooks_target is None:
        arguments.hooks_target = "plugin" if arguments.bundle_dir else "repo"
    return arguments


def main(argv: Sequence[str] | None = None, environment: Mapping[str, str] | None = None) -> int:
    arguments = _parse_arguments(sys.argv[1:] if argv is None else argv)
    try:
        outputs = plan(arguments, os.environ if environment is None else environment)
    except (InstallError, OSError, yaml.YAMLError) as failure:
        print(f"install.py: refused: {failure}", file=sys.stderr)
        return 1
    for path, text in outputs.items():
        if arguments.dry_run:
            print(f"would write {path}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
